import { describe, expect, it, vi } from 'vitest'
import { render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import DailyPicks from '../src/components/DailyPicks.jsx'
import { DAILY_PICKS_STORAGE_KEY } from '../src/lib/dailyPicks.js'
import { completedScenario, makeScenario, resultTime, selectionTime } from './fixtures/dailyPicks.js'

function setClock(value) { return vi.spyOn(Date, 'now').mockReturnValue(value.getTime()) }
function saved() { return JSON.parse(window.localStorage.getItem(DAILY_PICKS_STORAGE_KEY)) }

async function enterWager(user, stake = '100', odds = '1.30') {
  await user.type(screen.getByLabelText('Stake (₦)'), stake)
  await user.type(screen.getByLabelText('Decimal odds'), odds)
}

describe('daily pick and private bet journal', () => {
  it('saves one verified selection without assuming that a bet was placed', async () => {
    setClock(selectionTime)
    const s = makeScenario()
    render(<DailyPicks feed={s.feed} tracker={s.tracker} />)
    expect(await screen.findByText('SAVED MODEL SELECTION')).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'Alpha vs Beta' })).toBeInTheDocument()
    expect(saved().picks).toHaveLength(1)
    expect(saved().picks[0].bet).toBeNull()
    expect(screen.getByText('No actual bet recorded.')).toBeInTheDocument()
    expect(screen.getByText(/Europa League is not covered/)).toBeInTheDocument()
  })

  it('calculates a hypothetical return and only saves a bet after explicit confirmation', async () => {
    setClock(selectionTime)
    const s = makeScenario()
    const user = userEvent.setup()
    render(<DailyPicks feed={s.feed} tracker={s.tracker} />)
    await screen.findByText('SAVED MODEL SELECTION')
    await enterWager(user)
    expect(screen.getByText('₦130.00')).toBeInTheDocument()
    expect(screen.getByText('+₦30.00')).toBeInTheDocument()
    expect(screen.getByText(/whole ₦100.00 stake may be lost/)).toBeInTheDocument()
    expect(saved().picks[0].bet).toBeNull()
    await user.click(screen.getByRole('button', { name: /I placed this single/i }))
    expect(saved().picks[0].bet).toMatchObject({ stakeKobo: 10_000, oddsHundredths: 130, voidedAt: null })
    expect(screen.getByText(/No bet was placed by this site/)).toBeInTheDocument()
    expect(screen.getByText(/You recorded ₦100.00 at 1.30/)).toBeInTheDocument()
  })

  it('enforces the ₦100 daily limit and requires user-entered odds', async () => {
    setClock(selectionTime)
    const s = makeScenario()
    const user = userEvent.setup()
    render(<DailyPicks feed={s.feed} tracker={s.tracker} />)
    await screen.findByText('SAVED MODEL SELECTION')
    await enterWager(user, '100.01', '1.30')
    expect(screen.getByText(/Enter a stake from ₦0.01 to ₦100.00/)).toBeInTheDocument()
    expect(screen.getByRole('button', { name: /I placed this single/i })).toBeDisabled()
    expect(saved().picks[0].bet).toBeNull()
    await user.clear(screen.getByLabelText('Stake (₦)'))
    await user.type(screen.getByLabelText('Stake (₦)'), '100')
    await user.clear(screen.getByLabelText('Decimal odds'))
    expect(screen.getByText(/Enter decimal odds/)).toBeInTheDocument()
    expect(screen.getByRole('button', { name: /I placed this single/i })).toBeDisabled()
  })

  it('shows delayed scores and estimated net, permits a manual void, and keeps model accuracy separate', async () => {
    const clock = setClock(selectionTime)
    const s = makeScenario()
    const user = userEvent.setup()
    const first = render(<DailyPicks feed={s.feed} tracker={s.tracker} />)
    await screen.findByText('SAVED MODEL SELECTION')
    await enterWager(user)
    await user.click(screen.getByRole('button', { name: /I placed this single/i }))
    first.unmount()
    clock.mockReturnValue(resultTime.getTime())
    const done = completedScenario(s)
    render(<DailyPicks feed={done.feed} tracker={done.tracker} />)
    expect(screen.getByText('Model pick correct')).toBeInTheDocument()
    expect(screen.getByText('Reported score 2–0')).toBeInTheDocument()
    expect(screen.getByText(/Estimated return ₦130.00 · profit \+₦30.00/)).toBeInTheDocument()
    expect(screen.getByText('EST. NET / 1 SCORED BET')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /Mark bet void for Alpha/i }))
    expect(screen.getByText(/Marked void by you/)).toBeInTheDocument()
    expect(screen.getByText('EST. NET / 0 SCORED BETS')).toBeInTheDocument()
    expect(screen.getByText('Model pick correct')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /Undo void for Alpha/i }))
    expect(screen.getByText(/Estimated return ₦130.00 · profit \+₦30.00/)).toBeInTheDocument()
  })

  it('does not show false zero accuracy or profit when a later result check fails', async () => {
    const clock = setClock(selectionTime)
    const s = makeScenario()
    const first = render(<DailyPicks feed={s.feed} tracker={s.tracker} />)
    await screen.findByText('SAVED MODEL SELECTION')
    first.unmount()
    clock.mockReturnValue(resultTime.getTime())
    const done = completedScenario(s)
    render(<DailyPicks feed={done.feed} tracker={{ ...done.tracker, loadFailed: true }} />)
    expect(screen.getByText('— / —')).toBeInTheDocument()
    expect(screen.getByText(/Results cannot currently be checked/)).toBeInTheDocument()
    expect(screen.getByText('Result status unavailable')).toBeInTheDocument()
    expect(screen.queryByText('Model pick correct')).not.toBeInTheDocument()
  })

  it('does not make or backfill a daily selection for unverified, demo or past fixtures', async () => {
    const clock = setClock(selectionTime)
    const s = makeScenario()
    const view = render(<DailyPicks feed={s.feed} tracker={{ ...s.tracker, data: s.initial }} />)
    expect(screen.getByText('NO PICK FOR NOW.')).toBeInTheDocument()
    expect(window.localStorage.getItem(DAILY_PICKS_STORAGE_KEY)).toBeNull()
    view.rerender(<DailyPicks feed={{ status: 'demo' }} tracker={s.tracker} />)
    expect(screen.getByText('A PICK ISN’T AVAILABLE.')).toBeInTheDocument()
    expect(window.localStorage.getItem(DAILY_PICKS_STORAGE_KEY)).toBeNull()
    view.unmount()
    clock.mockReturnValue(s.fixtures[0].kickoffTimestamp + 1)
    render(<DailyPicks feed={s.feed} tracker={s.tracker} />)
    expect(screen.getByText('NO PICK FOR NOW.')).toBeInTheDocument()
    expect(window.localStorage.getItem(DAILY_PICKS_STORAGE_KEY)).toBeNull()
  })

  it('does not silently replace malformed local history or claim that it saved a pick', () => {
    setClock(selectionTime)
    const s = makeScenario()
    window.localStorage.setItem(DAILY_PICKS_STORAGE_KEY, '{bad json')
    render(<DailyPicks feed={s.feed} tracker={s.tracker} />)
    expect(screen.getByText(/Your local daily record could not be read/)).toBeInTheDocument()
    expect(screen.getByText('MODEL SELECTION · NOT SAVED')).toBeInTheDocument()
    expect(window.localStorage.getItem(DAILY_PICKS_STORAGE_KEY)).toBe('{bad json')
    expect(screen.queryByRole('button', { name: /I placed this single/i })).not.toBeInTheDocument()
  })

  it('shows unavailable tracking when writes fail and still allows a hypothetical calculation', async () => {
    setClock(selectionTime)
    const s = makeScenario()
    const user = userEvent.setup()
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('storage full') })
    render(<DailyPicks feed={s.feed} tracker={s.tracker} />)
    expect(await screen.findByText(/Browser storage is unavailable or full/)).toBeInTheDocument()
    expect(screen.getByText('MODEL SELECTION · NOT SAVED')).toBeInTheDocument()
    await enterWager(user, '50', '1.30')
    expect(screen.getByText('₦65.00')).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: /I placed this single/i })).not.toBeInTheDocument()
  })

  it('stops recording when the latest fixture no longer matches', async () => {
    setClock(selectionTime)
    const s = makeScenario()
    const user = userEvent.setup()
    const view = render(<DailyPicks feed={s.feed} tracker={s.tracker} />)
    await screen.findByText('SAVED MODEL SELECTION')
    await enterWager(user)
    view.rerender(<DailyPicks feed={{ ...s.feed, fixtures: [{ ...s.fixtures[0], time: '19:00' }] }} tracker={s.tracker} />)
    expect(screen.getByRole('button', { name: /I placed this single/i })).toBeDisabled()
    expect(saved().picks[0].bet).toBeNull()
  })

  it('restores an earlier same-day bet over a newly auto-saved copy of the same suggestion', async () => {
    const clock = setClock(selectionTime)
    const s = makeScenario()
    const user = userEvent.setup()
    const first = render(<DailyPicks feed={s.feed} tracker={s.tracker} />)
    await screen.findByText('SAVED MODEL SELECTION')
    await enterWager(user, '50', '1.30')
    await user.click(screen.getByRole('button', { name: /I placed this single/i }))
    const backup = saved()
    first.unmount()
    window.localStorage.removeItem(DAILY_PICKS_STORAGE_KEY)
    clock.mockReturnValue(selectionTime.getTime() + 30 * 60 * 1000)
    render(<DailyPicks feed={s.feed} tracker={s.tracker} />)
    await screen.findByText('SAVED MODEL SELECTION')
    expect(saved().picks[0].bet).toBeNull()
    await user.upload(screen.getByLabelText('Import daily picks backup'), new File([JSON.stringify(backup)], 'backup.json', { type: 'application/json' }))
    expect(await screen.findByText(/updated 1 matching day/)).toBeInTheDocument()
    expect(saved()).toEqual(backup)
    expect(screen.getByText(/You recorded ₦50.00 at 1.30/)).toBeInTheDocument()
  })

  it('imports a private backup additively and refuses a conflicting day', async () => {
    const clock = setClock(selectionTime)
    const s = makeScenario()
    const user = userEvent.setup()
    const first = render(<DailyPicks feed={s.feed} tracker={s.tracker} />)
    await screen.findByText('SAVED MODEL SELECTION')
    const original = saved()
    await enterWager(user)
    await user.click(screen.getByRole('button', { name: /I placed this single/i }))
    const withBet = saved()
    const conflicting = structuredClone(withBet)
    conflicting.picks[0].bet.stakeKobo = 5000
    const input = screen.getByLabelText('Import daily picks backup')
    await user.upload(input, new File([JSON.stringify(conflicting)], 'backup.json', { type: 'application/json' }))
    expect(await screen.findByText(/backup conflicts with the existing record/)).toBeInTheDocument()
    expect(saved()).toEqual(withBet)
    await user.upload(input, new File([JSON.stringify(original)], 'earlier.json', { type: 'application/json' }))
    expect(await screen.findByText(/Imported 0 new picks and updated 0 matching days/)).toBeInTheDocument()
    expect(saved()).toEqual(withBet)
    first.unmount()
    window.localStorage.removeItem(DAILY_PICKS_STORAGE_KEY)
    clock.mockReturnValue(resultTime.getTime())
    const done = completedScenario(s)
    render(<DailyPicks feed={done.feed} tracker={done.tracker} />)
    await user.upload(screen.getByLabelText('Import daily picks backup'), new File([JSON.stringify(withBet)], 'backup.json', { type: 'application/json' }))
    expect(await screen.findByText(/Imported 1 new pick/)).toBeInTheDocument()
    expect(saved()).toEqual(withBet)
    const history = screen.getByRole('heading', { name: 'HOW DID THE PICKS GO?' }).closest('.daily-history')
    expect(within(history).getByText('Model pick correct')).toBeInTheDocument()
  })
})
